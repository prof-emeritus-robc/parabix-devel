void DetermineNFC_WorkSelection(PipelineBuilder & P, StreamSet * U8_Basis, StreamSet * WorkSelectionMask) {
    StreamSet * NFC_Candidates = P.CreateStreamSet(2, 1);
    P.CreateKernelCall<NFC_CandidateClass>(U8_Basis, NFC_Candidates);
    SHOW_BIXNUM(NFC_Candidates);

    StreamSet * NFC_WorkItems = P.CreateStreamSet(1, 1);
    P.CreateKernelCall<NFC_Focus>(U8_Basis, NFC_Candidates, NFC_WorkItems);
    SHOW_STREAM(NFC_WorkItems);

    StreamSet * const u8index = P.CreateStreamSet(1, 1);
    P.CreateKernelCall<UTF8_index>(U8_Basis, u8index);
    SHOW_STREAM(u8index);

    P.CreateKernelCall<U8Spans>(NFC_WorkItems, u8index, WorkSelectionMask, BitMovementMode::Advance);
    SHOW_STREAM(WorkSelectionMask);
}

void NFC_Transform(PipelineBuilder & P, StreamSet * U8_Basis, StreamSet * TransformedBasis, StreamSet * ValidWorkMask,
                   StreamSet * WorkMask) {
    StreamSet * const InsertionBixNum = P.CreateStreamSet(4, 1);
    P.CreateKernelCall<NFC_Initial_Insertion>(U8_Basis, InsertionBixNum, WorkMask);
    SHOW_BIXNUM(InsertionBixNum);

    StreamSet * const ExpansionMask = P.CreateStreamSet(1, 1);
    InsertionSpreadMask(P, InsertionBixNum, ExpansionMask, kernel::InsertPosition::After);
    SHOW_STREAM(ExpansionMask);

    StreamSet * const WorkingBasis = P.CreateStreamSet(8, 1);
    SpreadByMask(P, ExpansionMask, U8_Basis, WorkingBasis);

    NFC_WorkingSpaceTransform(P, ExpansionMask, WorkingBasis, ValidWorkMask, TransformedBasis);
}

void NFC_WorkPlacement(PipelineBuilder & P, StreamSet * U8_Basis, StreamSet * WorkSelectionMask,
                       StreamSet * ValidWorkMask, StreamSet * WorkPlacementMask) {
    // The working space of the work regions, in the source expanded as for the
    // transform of the work regions.
    StreamSet * const InsertionBixNum = P.CreateStreamSet(4, 1);
    P.CreateKernelCall<NFC_Initial_Insertion>(U8_Basis, InsertionBixNum, WorkSelectionMask);
    SHOW_BIXNUM(InsertionBixNum);

    StreamSet * const SourceExpansionMask = P.CreateStreamSet(1, 1);
    InsertionSpreadMask(P, InsertionBixNum, SourceExpansionMask, kernel::InsertPosition::After);
    SHOW_STREAM(SourceExpansionMask);

    StreamSet * const ExpandedWorkMask = P.CreateStreamSet(1, 1);
    ExpandFilter(P, SourceExpansionMask, WorkSelectionMask, ExpandedWorkMask);
    SHOW_STREAM(ExpandedWorkMask);

    // The positions of the expanded source that remain: unmodified bytes and
    // the valid positions of the working space.
    StreamSet * const FinalWorkSelectionMask = P.CreateStreamSet(1, 1);
    ExpandFilter(P, ExpandedWorkMask, ValidWorkMask, FinalWorkSelectionMask);
    SHOW_STREAM(FinalWorkSelectionMask);

    FilterByMask(P, FinalWorkSelectionMask, ExpandedWorkMask, WorkPlacementMask);
    SHOW_STREAM(WorkPlacementMask);
}

FocusedTransform NFC_FocusedTransform(const FocusOptions & options) {
    return FocusedTransform(options,
        [](PipelineBuilder & P, StreamSet * basis, StreamSet * workMask) {
            DetermineNFC_WorkSelection(P, basis, workMask);
        },
        [](PipelineBuilder & P, StreamSet * basis, StreamSet * workMask, StreamSet * validMask, StreamSet * placementMask) {
            NFC_WorkPlacement(P, basis, workMask, validMask, placementMask);
        },
        [](PipelineBuilder & P, StreamSet * basis, StreamSet * transformedBasis, StreamSet * validMask) {
            NFC_Transform(P, basis, transformedBasis, validMask);
        });
}
